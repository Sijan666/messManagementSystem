export const downloadSummaryPDF = async (req, res) => {
  try {
    const activeMembers = await User.find({ status: 'active' }).select('name email');
    const totalActiveMembers = activeMembers.length;

    const expenses = await Expense.find();
    let totalBazaarExpense = 0;
    let totalUtilityExpense = 0;
    let totalHouseRentExpense = 0;
    let totalPersonalExpense = 0;

    const userExemptedCostMap = new Map();
    const userPersonalCostMap = new Map();

    expenses.forEach((expense) => {
      const amt = Number(expense.amount) || 0;
      if (expense.category === 'Personal' && expense.assignedTo) {
        totalPersonalExpense += amt;
        const uId = expense.assignedTo.toString();
        userPersonalCostMap.set(uId, (userPersonalCostMap.get(uId) || 0) + amt);
        return;
      }

      let perPersonShare = 0;
      if (totalActiveMembers > 0) {
        const payingMembersCount = totalActiveMembers - (expense.exemptedUsers?.length || 0);
        perPersonShare = payingMembersCount > 0 ? amt / payingMembersCount : 0;
      }

      if (expense.exemptedUsers && expense.exemptedUsers.length > 0) {
        expense.exemptedUsers.forEach((uId) => {
          const idStr = uId.toString();
          userExemptedCostMap.set(idStr, (userExemptedCostMap.get(idStr) || 0) + perPersonShare);
        });
      }

      if (expense.category === 'Bazaar') {
        totalBazaarExpense += amt;
      } else if (expense.category === 'Utility') {
        totalUtilityExpense += amt;
      } else if (expense.category === 'House Rent') {
        totalHouseRentExpense += amt;
      }
    });

    const meals = await Meal.find();
    const userMealMap = new Map();
    let totalMealsConsumed = 0;

    meals.forEach((meal) => {
      const uId = meal.userId.toString();
      const count = calculateTotalMeals(meal);
      totalMealsConsumed += count;
      userMealMap.set(uId, (userMealMap.get(uId) || 0) + count);
    });

    const currentMealRate =
      totalMealsConsumed > 0 ? Number((totalBazaarExpense / totalMealsConsumed).toFixed(2)) : 0;
    const baseSharedUtilityPerMember =
      totalActiveMembers > 0 ? totalUtilityExpense / totalActiveMembers : 0;
    const baseSharedRentPerMember =
      totalActiveMembers > 0 ? totalHouseRentExpense / totalActiveMembers : 0;

    const deposits = await Deposit.find({ status: 'approved' });
    let totalDeposit = 0;
    const userDepositMap = new Map();

    deposits.forEach((dep) => {
      const uId = dep.userId.toString();
      const amt = Number(dep.amount) || 0;
      totalDeposit += amt;
      userDepositMap.set(uId, (userDepositMap.get(uId) || 0) + amt);
    });

    const overallTotalCost =
      totalBazaarExpense + totalUtilityExpense + totalHouseRentExpense + totalPersonalExpense;
    const overallBalance = totalDeposit - overallTotalCost;

    // ---- Member data ----
    const members = activeMembers.map((member) => {
      const memberId = member._id.toString();
      const meals = userMealMap.get(memberId) || 0;
      const deposit = userDepositMap.get(memberId) || 0;
      const mealCost = meals * currentMealRate;
      const shared =
        baseSharedUtilityPerMember +
        baseSharedRentPerMember -
        (userExemptedCostMap.get(memberId) || 0);
      const personal = userPersonalCostMap.get(memberId) || 0;
      const totalCost = Number((mealCost + shared + personal).toFixed(2));
      const balance = Number((deposit - totalCost).toFixed(2));

      return { name: member.name, meals, deposit, mealCost, shared, personal, totalCost, balance };
    });

    const sum = (key) => members.reduce((s, m) => s + m[key], 0);
    const signed = (n) => `${n >= 0 ? '+' : '-'}${formatNum(Math.abs(n))}`;

    // ---- Document ----
    const doc = new PDFDocument({ margin: 30, size: 'A4', bufferPages: true });
    const now = new Date();
    const currentMonth = now.toLocaleString('en-US', { month: 'long', year: 'numeric' });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader(
      'Content-Disposition',
      `attachment; filename=Mess_Report_${currentMonth.replace(' ', '_')}.pdf`
    );
    doc.pipe(res);

    // Header
    drawHeader(doc, {
      monthLabel: currentMonth,
      generatedBy: req.user.name,
      role: req.user.role,
    });

    // Quick summary boxes
    drawSummaryBoxes(doc, [
      { label: 'Total Deposit', value: formatBDT(totalDeposit) },
      { label: 'Total Cost', value: formatBDT(overallTotalCost) },
      { label: 'Meal Rate', value: formatBDT(currentMealRate) },
      {
        label: 'Net Balance',
        value: `${overallBalance >= 0 ? '+' : '-'}${formatBDT(Math.abs(overallBalance))}`,
        color: overallBalance >= 0 ? COLORS.positive : COLORS.negative,
      },
    ]);

    // 1. Overall Summary
    drawSectionTitle(doc, '1. Overall Mess Summary');

    await drawTable(doc, {
      headers: ['Category', 'Amount / Count'],
      rows: [
        ['Total Deposit Collected', formatBDT(totalDeposit)],
        ['Total Cost (Including Personal)', formatBDT(overallTotalCost)],
        ['Total Bazaar Expense', formatBDT(totalBazaarExpense)],
        ['Total Utilities Expense', formatBDT(totalUtilityExpense)],
        ['Total House Rent', formatBDT(totalHouseRentExpense)],
        ['Total Personal Expense', formatBDT(totalPersonalExpense)],
        ['Total Meals Consumed', `${totalMealsConsumed} Meals`],
        ['Current Meal Rate', formatBDT(currentMealRate)],
        ['Active Members', `${totalActiveMembers}`],
      ],
      columnsSize: [300, 235],
      fontSize: 11,
    });

    // 2. Member Ledger
    drawSectionTitle(doc, '2. Member Account Ledger (BDT)');

    const ledgerRows = members.map((m) => [
      m.name,
      String(m.meals),
      formatNum(m.deposit),
      formatNum(m.mealCost),
      formatNum(m.shared),
      formatNum(m.personal),
      formatNum(m.totalCost),
      signed(m.balance),
    ]);

    const totalBalance = sum('deposit') - sum('totalCost');
    ledgerRows.push([
      'TOTAL',
      String(sum('meals')),
      formatNum(sum('deposit')),
      formatNum(sum('mealCost')),
      formatNum(sum('shared')),
      formatNum(sum('personal')),
      formatNum(sum('totalCost')),
      signed(totalBalance),
    ]);

    await drawTable(doc, {
      headers: ['Member', 'Meals', 'Deposit', 'Meal Cost', 'Shared', 'Personal', 'Total Cost', 'Balance'],
      rows: ledgerRows,
      columnsSize: [110, 40, 65, 65, 65, 62, 65, 63],
      fontSize: 10,
      highlightLastRow: true,
      balanceColumn: 7,
    });

    // Note
    doc
      .font('Helvetica-Oblique')
      .fontSize(9)
      .fillColor(COLORS.muted)
      .text(
        'Note: Balance = Deposit - Total Cost. (+) means the member has surplus, (-) means the member has dues.',
        doc.page.margins.left,
        doc.y,
        { width: pageWidth(doc) }
      );

    // Page numbers + footer on every page
    drawPageNumbers(doc);

    doc.end();
  } catch (error) {
    console.error('Summary PDF Error:', error);
    if (!res.headersSent) {
      return res.status(500).json({
        status: 'error',
        message: error.message || 'Failed to generate PDF document.',
      });
    }
  }
};