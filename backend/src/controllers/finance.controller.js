// ---------- PDF Theme & Helpers ----------
const COLORS = {
  primary: '#1e3a8a',
  primaryLight: '#dbeafe',
  border: '#374151',
  text: '#111827',
  muted: '#6b7280',
  zebra: '#f3f4f6',
  white: '#ffffff',
  positive: '#047857',
  negative: '#b91c1c',
  totalBg: '#e5e7eb',
};

const formatBDT = (n) =>
  `BDT ${Number(n || 0).toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;

const formatNum = (n) =>
  Number(n || 0).toLocaleString('en-US', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });

const pageWidth = (doc) =>
  doc.page.width - doc.page.margins.left - doc.page.margins.right;

const drawHeader = (doc, { monthLabel, generatedBy, role }) => {
  const left = doc.page.margins.left;
  const width = pageWidth(doc);

  doc.rect(left, 30, width, 90).fillAndStroke(COLORS.primary, COLORS.border);

  doc
    .fillColor(COLORS.white)
    .font('Helvetica-Bold')
    .fontSize(26)
    .text('MESS FINANCIAL REPORT', left, 45, { width, align: 'center' });

  doc
    .font('Helvetica')
    .fontSize(12)
    .text(`Report Month: ${monthLabel}`, left, 80, { width, align: 'center' });

  doc
    .fontSize(10)
    .text(
      `Generated By: ${generatedBy} (${role})  |  Date: ${new Date().toLocaleDateString('en-GB', {
        day: '2-digit',
        month: 'short',
        year: 'numeric',
      })}`,
      left,
      98,
      { width, align: 'center' }
    );

  doc.fillColor(COLORS.text);
  doc.y = 140;
  doc.x = left;
};

const drawSectionTitle = (doc, title) => {
  const left = doc.page.margins.left;
  const width = pageWidth(doc);
  const y = doc.y;

  doc.rect(left, y, width, 26).fillAndStroke(COLORS.primaryLight, COLORS.border);
  doc
    .fillColor(COLORS.primary)
    .font('Helvetica-Bold')
    .fontSize(14)
    .text(title, left + 10, y + 6, { width: width - 20 });

  doc.fillColor(COLORS.text);
  doc.y = y + 26 + 10;
  doc.x = left;
};

const drawSummaryBoxes = (doc, items) => {
  const left = doc.page.margins.left;
  const boxWidth = pageWidth(doc) / items.length;
  const y = doc.y;
  const height = 58;

  items.forEach((item, i) => {
    const x = left + i * boxWidth;
    doc.lineWidth(1).strokeColor(COLORS.border).rect(x, y, boxWidth, height).stroke();

    doc
      .fillColor(COLORS.muted)
      .font('Helvetica')
      .fontSize(10)
      .text(item.label, x, y + 10, { width: boxWidth, align: 'center' });

    doc
      .fillColor(item.color || COLORS.primary)
      .font('Helvetica-Bold')
      .fontSize(13)
      .text(item.value, x, y + 30, { width: boxWidth, align: 'center' });
  });

  doc.fillColor(COLORS.text);
  doc.y = y + height + 20;
  doc.x = left;
};

// Full-border table (outer + every row + every column)
const drawTable = async (
  doc,
  { headers, rows, columnsSize, fontSize = 11, highlightLastRow = false, balanceColumn = null }
) => {
  const left = doc.page.margins.left;
  const width = pageWidth(doc);

  await doc.table(
    { headers, rows },
    {
      x: left,
      width,
      columnsSize,
      padding: 6,
      divider: {
        header: { disabled: false, width: 1, opacity: 1 },
        horizontal: { disabled: false, width: 0.8, opacity: 1 },
      },
      prepareHeader: () => {
        doc.font('Helvetica-Bold').fontSize(fontSize).fillColor(COLORS.primary);
      },
      prepareRow: (row, indexColumn, indexRow, rectRow, rectCell) => {
        const isLast = highlightLastRow && indexRow === rows.length - 1;

        if (indexColumn === 0) {
          if (isLast) {
            doc.addBackground(rectRow, COLORS.totalBg, 1);
          } else if (indexRow % 2 === 0) {
            doc.addBackground(rectRow, COLORS.zebra, 1);
          }
        }

        doc.font(isLast ? 'Helvetica-Bold' : 'Helvetica').fontSize(fontSize).fillColor(COLORS.text);

        // Balance column: green for +, red for -
        if (balanceColumn !== null && indexColumn === balanceColumn) {
          const val = String(row[balanceColumn] || '');
          if (val.startsWith('+')) doc.fillColor(COLORS.positive).font('Helvetica-Bold');
          else if (val.startsWith('-')) doc.fillColor(COLORS.negative).font('Helvetica-Bold');
        }

        const { x, y, width: w, height: h } = rectCell;
        doc.lineWidth(0.8).strokeColor(COLORS.border).rect(x, y, w, h).stroke();
      },
    }
  );
  doc.moveDown(1.5);
};

const drawPageNumbers = (doc) => {
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);

    const oldBottom = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;

    const y = doc.page.height - 30;
    const left = doc.page.margins.left;
    const width = pageWidth(doc);

    doc
      .moveTo(left, y - 8)
      .lineTo(left + width, y - 8)
      .lineWidth(0.8)
      .strokeColor(COLORS.border)
      .stroke();

    doc
      .font('Helvetica-Oblique')
      .fontSize(9)
      .fillColor(COLORS.muted)
      .text('System Generated Report - Mess Management Portal', left, y, {
        width: width / 2,
        align: 'left',
        lineBreak: false,
      });

    doc
      .font('Helvetica')
      .text(`Page ${i + 1} of ${range.count}`, left + width / 2, y, {
        width: width / 2,
        align: 'right',
        lineBreak: false,
      });

    doc.page.margins.bottom = oldBottom;
  }
};

// ---------- Dashboard Summary (unchanged) ----------
export const getDashboardSummary = async (req, res) => {
  try {
    const activeMembers = await User.find({ status: 'active' }).select('name email role');
    const totalActiveMembers = activeMembers.length;

    const expenses = await Expense.find();
    let totalBazaarExpense = 0;
    let totalUtilityExpense = 0;
    let totalHouseRentExpense = 0;
    let totalPersonalExpense = 0;

    const userExemptedCostMap = new Map();
    const userPersonalCostMap = new Map();

    expenses.forEach((expense) => {
      const amt = Number(expense.amount) || 0;

      if (expense.category === 'Personal' && expense.assignedTo) {
        totalPersonalExpense += amt;
        const uId = expense.assignedTo.toString();
        userPersonalCostMap.set(uId, (userPersonalCostMap.get(uId) || 0) + amt);
        return;
      }

      let perPersonShare = 0;
      if (totalActiveMembers > 0) {
        const payingMembersCount = totalActiveMembers - (expense.exemptedUsers?.length || 0);
        perPersonShare = payingMembersCount > 0 ? amt / payingMembersCount : 0;
      }

      if (expense.exemptedUsers && expense.exemptedUsers.length > 0) {
        expense.exemptedUsers.forEach((uId) => {
          const idStr = uId.toString();
          userExemptedCostMap.set(idStr, (userExemptedCostMap.get(idStr) || 0) + perPersonShare);
        });
      }

      if (expense.category === 'Bazaar') {
        totalBazaarExpense += amt;
      } else if (expense.category === 'Utility') {
        totalUtilityExpense += amt;
      } else if (expense.category === 'House Rent') {
        totalHouseRentExpense += amt;
      }
    });

    const totalCost =
      totalBazaarExpense + totalUtilityExpense + totalHouseRentExpense + totalPersonalExpense;

    const meals = await Meal.find();
    const userMealMap = new Map();
    let totalMealsConsumed = 0;

    meals.forEach((meal) => {
      const uId = meal.userId.toString();
      const count = calculateTotalMeals(meal);
      totalMealsConsumed += count;
      userMealMap.set(uId, (userMealMap.get(uId) || 0) + count);
    });

    const currentMealRate =
      totalMealsConsumed > 0 ? Number((totalBazaarExpense / totalMealsConsumed).toFixed(2)) : 0;

    const baseSharedUtilityPerMember =
      totalActiveMembers > 0 ? totalUtilityExpense / totalActiveMembers : 0;
    const baseSharedRentPerMember =
      totalActiveMembers > 0 ? totalHouseRentExpense / totalActiveMembers : 0;

    const deposits = await Deposit.find({ status: 'approved' });
    let totalDeposit = 0;
    const userDepositMap = new Map();

    deposits.forEach((dep) => {
      const uId = dep.userId.toString();
      const amt = Number(dep.amount) || 0;
      totalDeposit += amt;
      userDepositMap.set(uId, (userDepositMap.get(uId) || 0) + amt);
    });

    const individualBalances = activeMembers.map((member) => {
      const memberId = member._id.toString();
      const individualMeals = userMealMap.get(memberId) || 0;
      const individualDeposit = userDepositMap.get(memberId) || 0;

      const mealCost = individualMeals * currentMealRate;
      const exemptionDeduction = userExemptedCostMap.get(memberId) || 0;
      const trueSharedCost =
        baseSharedUtilityPerMember + baseSharedRentPerMember - exemptionDeduction;
      const personalExtraCost = userPersonalCostMap.get(memberId) || 0;

      const totalMemberCost = Number((mealCost + trueSharedCost + personalExtraCost).toFixed(2));
      const balance = Number((individualDeposit - totalMemberCost).toFixed(2));

      return {
        userId: member._id,
        name: member.name,
        email: member.email,
        role: member.role,
        totalDeposit: individualDeposit,
        totalMeals: individualMeals,
        mealCost: Number(mealCost.toFixed(2)),
        utilityAndRentShare: Number(trueSharedCost.toFixed(2)),
        personalExtraCost: Number(personalExtraCost.toFixed(2)),
        totalCost: totalMemberCost,
        balance,
      };
    });

    const loggedInUserBalance = individualBalances.find(
      (m) => m.userId.toString() === req.user._id.toString()
    ) || {
      userId: req.user._id,
      name: req.user.name,
      email: req.user.email,
      role: req.user.role,
      totalDeposit: userDepositMap.get(req.user._id.toString()) || 0,
      totalMeals: userMealMap.get(req.user._id.toString()) || 0,
      mealCost: 0,
      utilityAndRentShare: 0,
      personalExtraCost: 0,
      totalCost: 0,
      balance: userDepositMap.get(req.user._id.toString()) || 0,
    };

    return res.status(200).json({
      status: 'success',
      data: {
        summary: {
          totalDeposit: Number(totalDeposit.toFixed(2)),
          totalCost: Number(totalCost.toFixed(2)),
          totalBazaarExpense: Number(totalBazaarExpense.toFixed(2)),
          totalUtilityExpense: Number(totalUtilityExpense.toFixed(2)),
          totalHouseRentExpense: Number(totalHouseRentExpense.toFixed(2)),
          totalPersonalExpense: Number(totalPersonalExpense.toFixed(2)),
          totalMeals: totalMealsConsumed,
          currentMealRate,
          totalActiveMembers,
        },
        individualBalances,
        userSummary: loggedInUserBalance,
      },
    });
  } catch (error) {
    return res.status(500).json({
      status: 'error',
      message: error.message || 'Failed to compute financial summary.',
    });
  }
};

